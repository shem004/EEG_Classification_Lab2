def run_config(
    name, model_type='EEGNet', act='relu', dropout=0.25, alpha=1.0,
    negative_slope=0.01, F1=16, D=2, F2=32, kernel_length=51,
    lr=0.001, epochs=350, patience=50, use_sched=True
):
    torch.manual_seed(42)
    np.random.seed(42)

    args = argparse.Namespace(num_epochs=epochs, batch_size=64, lr=lr)
    if model_type == 'EEGNet':
        model = EEGNet(
            activation=act, dropout=dropout, alpha=alpha,
            negative_slope=negative_slope, F1=F1, D=D, F2=F2,
            kernel_length=kernel_length
        ).to(device)
    else:
        model = DeepConvNet(
            activation=act, dropout=dropout, alpha=alpha,
            negative_slope=negative_slope
        ).to(device)

    criterion = nn.CrossEntropyLoss().to(device)
    #try other optimizer
    #optimizer = optim.RMSprop(model.parameters(),lr = lr, momentum = 0.6) #ex2
    optimizer = optim.Adam(model.parameters(), lr=lr, weight_decay=0.001) #ex1
    #try scheduler
    #scheduler = optim.lr_scheduler.MultiStepLR(optimizer, milestones=[100,300,500], gamma=0.1)if use_sched else None #ex2
    scheduler = optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=epochs, eta_min=1e-5) if use_sched else None #ex1

    save_path = f'/content/drive/MyDrive/lab2_EEG_classification/weights/{name}.pt'
    train_acc, train_loss, test_acc, best_acc, best_ep = train(
        model, train_loader, criterion, optimizer, args,
        scheduler=scheduler, patience=patience, save_path=save_path
    )
    print(f"--> [{name}] Best Peak Test Acc: {best_acc:.2f}% (at Epoch {best_ep}/{len(test_acc)})\n")

    return {
        'name': name, 'model_type': model_type, 'act': act,
        'dropout': str(dropout), 'F1_D_F2': f"{F1}-{D}-{F2}", 'kernel': kernel_length,
        'lr': lr, 'best_epoch': best_ep, 'stopped_epoch': len(test_acc),
        'max_train_acc': round(max(train_acc), 2), 'best_test_acc': round(best_acc, 2),
        'train_acc': train_acc, 'train_loss': train_loss, 'test_acc': test_acc,
        'model_obj': model
    }

def plot_experiment_graphs(results_list, exp_title):
    """Generates 3 separate clean graphs for the experiment: 1. Test Acc, 2. Train Acc, 3. Train Loss"""
    test_acc_dict = {r['name']: r['test_acc'] for r in results_list}
    train_acc_dict = {r['name']: r['train_acc'] for r in results_list}
    train_loss_dict = {r['name']: r['train_loss'] for r in results_list}

    plot_test_acc(test_acc_dict, title=f"{exp_title} - Testing Accuracy")
    plot_train_acc(train_acc_dict, title=f"{exp_title} - Training Accuracy")
    plot_train_loss(train_loss_dict, title=f"{exp_title} - Training Loss")



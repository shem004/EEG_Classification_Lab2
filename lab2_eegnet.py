def train(model, loader, criterion, optimizer, args, scheduler=None, patience=50, save_path='/content/drive/MyDrive/lab2_EEG_classification/weights/best.pt'):
    # Make sure parent directory of our target save path exists
    parent_dir = os.path.dirname(save_path)
    if parent_dir:
        os.makedirs(parent_dir, exist_ok=True)

    best_acc = 0.0
    best_epoch = 0
    best_wts = deepcopy(model.state_dict())
    patience_counter = 0

    avg_acc_list = []
    test_acc_list = []
    avg_loss_list = []

    pbar = tqdm(range(1, args.num_epochs + 1), desc=os.path.basename(save_path))
    for epoch in pbar:
        model.train()
        with torch.set_grad_enabled(True):
            avg_acc = 0.0
            avg_loss = 0.0
            for i, data in enumerate(loader, 0):
                inputs, labels = data
                inputs = inputs.to(device)
                labels = labels.to(device)

                optimizer.zero_grad()
                outputs = model.forward(inputs)
                loss = criterion(outputs, labels)
                loss.backward()
                optimizer.step()
                avg_loss += loss.item()
                _, pred = torch.max(outputs.data, 1)
                avg_acc += pred.eq(labels).cpu().sum().item()

            if scheduler is not None:
                scheduler.step()

            avg_loss /= len(loader.dataset)
            avg_loss_list.append(avg_loss)
            avg_acc = (avg_acc / len(loader.dataset)) * 100
            avg_acc_list.append(avg_acc)

        test_acc = test(model, test_loader)
        test_acc_list.append(test_acc)

        # Checkpoint: only overwrite best_wts when peak test_acc improves
        if test_acc > best_acc:
            best_acc = test_acc
            best_epoch = epoch
            best_wts = deepcopy(model.state_dict())
            torch.save(best_wts, save_path)
            patience_counter = 0
        else:
            patience_counter += 1

        pbar.set_postfix({
            'Train': f'{avg_acc:.1f}%',
            'Test': f'{test_acc:.1f}%',
            'Best': f'{best_acc:.2f}% (Ep {best_epoch})',
            'Patience': f'{patience_counter}/{patience}'
        })

        # Early Stopping check
        if patience is not None and patience_counter >= patience:
            print(f"Early stopping triggered at Epoch {epoch}! Best Test Acc: {best_acc:.2f}% at Epoch {best_epoch}.")
            break

    # reload the best peak-accuracy checkpoint into the model, no keeping final weight
    model.load_state_dict(best_wts)
    torch.save(best_wts, save_path)
    return avg_acc_list, avg_loss_list, test_acc_list, best_acc, best_epoch


def test(model, loader):
    avg_acc = 0.0
    model.eval()
    with torch.set_grad_enabled(False):
        for inputs, labels in loader:
            inputs = inputs.to(device)
            outputs = model(inputs)
            _, pred = torch.max(outputs, 1)
            for i in range(len(labels)):
                if int(pred[i]) == int(labels[i]):
                    avg_acc += 1
        avg_acc = (avg_acc / len(loader.dataset)) * 100
    return avg_acc


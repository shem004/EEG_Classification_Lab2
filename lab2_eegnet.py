import torch.nn as nn

def make_activation(activation='elu', alpha=1.0, negative_slope=0.06):
    if activation == 'relu':
        return nn.ReLU()
    elif activation == 'leaky_relu':
        return nn.LeakyReLU(negative_slope=negative_slope)
    else:
        return nn.ELU(alpha=alpha)

